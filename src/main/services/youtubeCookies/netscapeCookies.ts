/**
 * Convert Electron session cookies into Netscape / Mozilla `cookies.txt`.
 *
 * yt-dlp `--cookies` expects this classic tab-separated format (not JSON).
 * Values are never logged here — callers must not dump the output string.
 */

import type { Cookie } from 'electron';

/** Domains yt-dlp needs for YouTube signed-in / age-gated streams. */
const YOUTUBE_COOKIE_DOMAIN_RE =
  /(^|\.)(youtube\.com|google\.com|googlevideo\.com|youtu\.be|ytimg\.com|ggpht\.com|googleusercontent\.com)$/i;

/** Cookie names that strongly indicate an authenticated Google/YouTube session. */
export const YOUTUBE_AUTH_COOKIE_NAMES = new Set([
  'LOGIN_INFO',
  '__Secure-1PSID',
  '__Secure-3PSID',
  'SID',
  'HSID',
  'SSID',
  'APISID',
  'SAPISID',
  '__Secure-1PAPISID',
  '__Secure-3PAPISID'
]);

/**
 * Returns true when `domain` belongs to the YouTube / Google cookie family.
 */
export function isYouTubeRelatedDomain(domain: string | undefined | null): boolean {
  if (!domain) return false;
  const normalized = domain.startsWith('.') ? domain.slice(1) : domain;
  return YOUTUBE_COOKIE_DOMAIN_RE.test(normalized);
}

/**
 * Filter Electron cookies down to YouTube/Google hosts used by yt-dlp.
 *
 * @param cookies - Raw cookies from `session.cookies.get`
 * @returns Subset safe to persist for YouTube downloads
 */
export function filterYouTubeCookies(cookies: Cookie[]): Cookie[] {
  return cookies.filter((c) => isYouTubeRelatedDomain(c.domain));
}

/**
 * Heuristic: enough auth cookies present to treat the session as logged in.
 * Why: Google may set dozens of cookies; requiring a full set is brittle with 2FA flows.
 *
 * @param cookies - Electron cookies (any domain; filtered internally)
 */
export function cookiesIndicateYouTubeLogin(cookies: Cookie[]): boolean {
  const relevant = filterYouTubeCookies(cookies);
  const names = new Set(relevant.map((c) => c.name));

  // Strong signals alone are enough.
  if (names.has('LOGIN_INFO') || names.has('__Secure-1PSID') || names.has('__Secure-3PSID')) {
    return true;
  }

  let hits = 0;
  for (const name of ['SID', 'HSID', 'SSID', 'APISID', 'SAPISID']) {
    if (names.has(name)) hits++;
  }
  return hits >= 3;
}

/**
 * Format a single cookie as one Netscape line.
 * Spec: domain, flag, path, secure, expiry, name, value (TAB-separated).
 */
function formatNetscapeLine(cookie: Cookie): string {
  const rawDomain = cookie.domain || '';
  // Leading-dot domains imply host-only=false (include subdomains).
  const domain =
    rawDomain.startsWith('.') || rawDomain.startsWith('www.')
      ? rawDomain.startsWith('.')
        ? rawDomain
        : `.${rawDomain}`
      : rawDomain.includes('.')
        ? `.${rawDomain}`
        : rawDomain;
  const includeSubdomains = domain.startsWith('.') ? 'TRUE' : 'FALSE';
  const pathPart = cookie.path && cookie.path.length > 0 ? cookie.path : '/';
  const secure = cookie.secure ? 'TRUE' : 'FALSE';
  // Session cookies: use 0 (session) so yt-dlp still sends them.
  const expiry =
    typeof cookie.expirationDate === 'number' && Number.isFinite(cookie.expirationDate)
      ? Math.max(0, Math.floor(cookie.expirationDate))
      : 0;
  const name = cookie.name ?? '';
  const value = cookie.value ?? '';
  // Netscape forbids tabs/newlines inside fields — strip defensively.
  const clean = (s: string) => s.replace(/[\t\r\n]/g, '');
  return [
    clean(domain),
    includeSubdomains,
    clean(pathPart),
    secure,
    String(expiry),
    clean(name),
    clean(value)
  ].join('\t');
}

/**
 * Build a Netscape HTTP Cookie File from Electron cookies.
 *
 * @param cookies - Prefer already-filtered YouTube cookies
 * @returns Full file body including header comments
 * @complexity O(N) time / O(N) space in cookie count
 */
export function electronCookiesToNetscape(cookies: Cookie[]): string {
  const lines: string[] = [
    '# Netscape HTTP Cookie File',
    '# This file was generated by Karaoke Live Station for yt-dlp.',
    '# Do not edit manually.',
    ''
  ];

  for (const cookie of cookies) {
    if (!cookie.name) continue;
    lines.push(formatNetscapeLine(cookie));
  }

  return `${lines.join('\n')}\n`;
}

/**
 * Lightweight validation of an on-disk Netscape cookies file.
 * Does not parse every field — checks size + presence of auth cookie names.
 */
export function netscapeFileLooksAuthenticated(fileContents: string): boolean {
  if (!fileContents || fileContents.length < 80) return false;
  // Reject empty / header-only exports.
  const dataLines = fileContents
    .split(/\r?\n/)
    .filter((line) => line.trim().length > 0 && !line.trim().startsWith('#'));
  if (dataLines.length === 0) return false;

  let authHits = 0;
  for (const line of dataLines) {
    const cols = line.split('\t');
    if (cols.length < 7) continue;
    const domain = cols[0] || '';
    const name = cols[5] || '';
    if (!isYouTubeRelatedDomain(domain)) continue;
    if (name === 'LOGIN_INFO' || name === '__Secure-1PSID' || name === '__Secure-3PSID') {
      return true;
    }
    if (YOUTUBE_AUTH_COOKIE_NAMES.has(name)) authHits++;
  }
  return authHits >= 3;
}
